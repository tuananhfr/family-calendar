// Generates src/core/api/schema.d.ts from a committed copy of the backend OpenAPI document.
// The frontend build never reads ../backend (ARC-02): refresh the copy by hand, then run `npm run gen:api`.
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const input = path.resolve(root, process.env.OPENAPI_FILE ?? "src/core/api/openapi.json");
const output = path.resolve(root, "src/core/api/schema.d.ts");

const doc = JSON.parse(await readFile(input, "utf8"));
const ast = await openapiTS(doc, { alphabetize: true });
const header = `// Generated by scripts/gen-api-types.mjs from ${path.relative(root, input).replaceAll("\\", "/")} — do not edit.\n`;
await writeFile(output, header + astToString(ast), "utf8");
console.log(`schema.d.ts written (${Object.keys(doc.paths ?? {}).length} paths)`);
